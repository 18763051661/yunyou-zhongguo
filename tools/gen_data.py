# 路线
lines.append("INSERT INTO route (id,name,subtitle,description,duration_minutes,difficulty,tags,suitable_for,cover_prompt,sort_no) VALUES")
name_to_spot = {sp["name"]: sp for sp in spots}
for rid,(nm, sub, desc, tags, suit, names) in enumerate(ROUTES, start=1):
    rspots = [name_to_spot[n] for n in names]
    dur = sum(40 if sp["cid"] != 6 else 90 for sp in rspots) + (len(rspots)-1)*30
    diff = max(CAT_DIFF[sp["cid"]] for sp in rspots)
    cover = f"{nm},中国旅游路线风景合集,高清风光摄影"
    lines.append(f"  ({rid},'{esc(nm)}','{esc(sub)}','{esc(desc)}',{dur},{diff},'{tags}','{suit}','{esc(cover)}',{rid})"
                 + ("," if rid < len(ROUTES) else ";"))
# 路线站点
lines.append("INSERT INTO route_spot (route_id,spot_id,day_no,step_no,stay_minutes,narration) VALUES")
rs_rows = []
for rid,(nm, sub, desc, tags, suit, names) in enumerate(ROUTES, start=1):
    rspots = [name_to_spot[n] for n in names]
    per_day = 4 if len(rspots) > 6 else (3 if len(rspots) > 4 else len(rspots))
    for idx, sp in enumerate(rspots, start=1):
        day = (idx-1)//per_day + 1
        step = (idx-1) % per_day + 1
        stay = 90 if sp["cid"] == 6 else (60 if sp["cid"] in (1,2) else 40)
        narr = route_narration(sp, idx, len(rspots), nm)
        rs_rows.append(f"({rid},{sp['id']},{day},{step},{stay},'{esc(narr)}')")
lines.append(",\n".join(rs_rows) + ";")
